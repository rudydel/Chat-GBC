GLYPHS = {k: v for k, v in GLYPHS.items() if v is not None}
ORDER = [' '] + [c for c in GLYPHS if c != ' ']


def tile_bytes(rows, invert=False):
    out = []
    for r in rows:
        r = r.ljust(5, ".")
        bits = 0
        for x, ch in enumerate(r[:5]):
            if ch == "#":
                bits |= 0x80 >> (x + 1)      # 1 px left margin
        if invert:
            bits ^= 0xFF
        out += [bits, bits]                   # both bitplanes -> color 3 (or 0)
    return out


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    n = len(ORDER)
    tiles = []
    for c in ORDER:
        tiles += tile_bytes(GLYPHS[c])
    for c in ORDER:
        tiles += tile_bytes(GLYPHS[c], invert=True)
    fmap = [0] * 128
    for i, c in enumerate(ORDER):
        fmap[ord(c)] = i
    with open(os.path.join(root, "gb/src/font.c"), "w") as f:
        f.write("/* Generated by tools/fontgen.py - do not edit. */\n#include \"font.h\"\n\n")
        f.write(f"const uint8_t font_tiles[{len(tiles)}] = {{\n")
        for i in range(0, len(tiles), 16):
            f.write("    " + ", ".join(f"0x{b:02X}" for b in tiles[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write(f"const uint8_t font_map[128] = {{\n")
        for i in range(0, 128, 16):
            f.write("    " + ", ".join(str(b) for b in fmap[i:i + 16]) + ",\n")
        f.write("};\n")
    with open(os.path.join(root, "gb/src/font.h"), "w") as f:
        f.write("/* Generated by tools/fontgen.py - do not edit. */\n#ifndef FONT_H\n#define FONT_H\n#include <stdint.h>\n")
        f.write(f"#define FONT_NGLYPHS {n}\n#define FONT_NTILES {2 * n}\n#define FONT_INV_OFFSET {n}\n")
        f.write("extern const uint8_t font_tiles[];\nextern const uint8_t font_map[128];\n")
        f.write("#define CHAR_TILE(c) (font_map[(uint8_t)(c) & 0x7F])\n#endif\n")
    with open(os.path.join(root, "tools/font_map.json"), "w") as f:
        json.dump({"tile_to_char": ORDER, "inv_offset": n}, f)
    print(f"font: {n} glyphs, {2 * n} tiles")


if __name__ == "__main__":
    main()
